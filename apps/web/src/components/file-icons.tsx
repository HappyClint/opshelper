export function getFileIcon(filename: string) {
  const ext = filename.split(".").pop()?.toLowerCase();
  switch (ext) {
    case "doc":
    case "docx":
      return <IconWord />;
    case "ppt":
    case "pptx":
      return <IconPPT />;
    case "xls":
    case "xlsx":
      return <IconExcel />;
    case "md":
      return <IconMarkdown />;
    case "json":
      return <IconJSON />;
    case "pdf":
      return <IconPDF />;
    default:
      return <IconFile />;
  }
}
